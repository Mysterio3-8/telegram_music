"""Починка кириллицы, приехавшей из источника в битой кодировке.

Откуда берётся: заливщик много лет назад сохранил тег в cp1251, а прочитан он
был как latin-1. Кириллическая «Р» (U+0420) в cp1251 это байт 0xC0, а в latin-1
байт 0xC0 — это «À». Так «Рядом быть» превращается в «Ðÿäîì áûòü».

Замер 14.08: по запросу «мияги там ямакаси» первым в выдаче стоял кандидат с
исполнителем «Ðÿäîì áûòü (AQUArecords…» — это видел человек в списке кнопок.

Починка безопасна по построению: осмысленный русский текст в latin-1 не
кодируется вовсе (кириллицы в этой кодировке нет), поэтому попытка обратного
преобразования на нормальной строке падает с ошибкой и мы её просто не трогаем.
Единственный риск — настоящий западноевропейский текст («Björk», «Café») мог бы
превратиться в кириллическую кашу, поэтому результат принимаем, только если он
действительно похож на кириллицу.
"""
import re

# Символы, в которые cp1251-кириллица превращается при чтении как latin-1:
# верхняя половина таблицы. Если их в строке нет, чинить нечего.
_SUSPICIOUS = re.compile(r"[À-ÿ-¿]")
_CYRILLIC = re.compile(r"[а-яёА-ЯЁ]")


def looks_broken(text: str) -> bool:
    """Похоже ли на кириллицу, прочитанную не в той кодировке."""
    if not text or _CYRILLIC.search(text):
        return False  # настоящая кириллица уже на месте — не трогаем
    return bool(_SUSPICIOUS.search(text))


def repair(text: str) -> str:
    """Возвращает починенный текст либо исходный, если чинить нечего или
    результат не стал похож на кириллицу."""
    if not looks_broken(text):
        return text
    try:
        fixed = text.encode("latin-1").decode("cp1251")
    except (UnicodeEncodeError, UnicodeDecodeError):
        return text
    # Принимаем, только если кириллицы стало заметно больше половины букв —
    # иначе это был обычный французский или исландский текст, и мы бы его
    # испортили.
    letters = [ch for ch in fixed if ch.isalpha()]
    if not letters:
        return text
    cyrillic = sum(1 for ch in letters if _CYRILLIC.match(ch))
    return fixed if cyrillic / len(letters) > 0.5 else text
